def dec(e):
    if not e:
        return ''
    t = str(e)
    n = t[0]
    o = ord(t[0])
    for ch in t[1:]:
        u0 = ord(ch)
        u = o - u0 if o >= u0 else o + 90 - u0
        n += chr(u + 32)
        o = u0
    return n

